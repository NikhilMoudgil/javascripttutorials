const month=3
switch (month) {
    case 1:
        console.log("January");
        break;
    case 2:
        console.log("Fab");
        break;
    case 3:
        console.log("Mar");
        break;
    case 4:
        console.log("apr");
        break;
    case 5:
        console.log("May");
        break;

    default:
        console.log("Please Enter a Value");
        
        break;
}
 // we can also use string as cases 